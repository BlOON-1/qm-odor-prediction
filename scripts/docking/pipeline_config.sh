#!/bin/bash
# Shared configuration for the complete docking and structural-analysis workflow.
# Every value can be overridden through an exported environment variable.

PIPELINE_CONFIG_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
PROJECT_ROOT="${PROJECT_ROOT:-${PIPELINE_PROJECT_DIR:-$(cd "$PIPELINE_CONFIG_DIR/.." && pwd -P)}}"
PIPELINE_PROJECT_DIR="${PIPELINE_PROJECT_DIR:-$PROJECT_ROOT}"

CONDA_BASE="${CONDA_BASE:?Set CONDA_BASE to the local Conda installation}"
POST_ENV_NAME="${POST_ENV_NAME:-sklearn}"

DOCK_CPUS="${DOCK_CPUS:-64}"
POST_CPUS="${POST_CPUS:-32}"
PLIP_PARALLEL="${PLIP_PARALLEL:-16}"

GA_RUN_TOTAL="${GA_RUN_TOTAL:-100}"
GA_NUM_EVALS="${GA_NUM_EVALS:-10000000}"
GA_NUM_GENERATIONS="${GA_NUM_GENERATIONS:-50000}"
GA_POP_SIZE="${GA_POP_SIZE:-300}"
RMSTOL="${RMSTOL:-2.0}"

RMSD_PRIMARY_CUTOFF="${RMSD_PRIMARY_CUTOFF:-2.0}"
RMSD_SENSITIVITY_CUTOFFS="${RMSD_SENSITIVITY_CUTOFFS:-1.5 2.0 2.5}"
SKIP_EXISTING="${SKIP_EXISTING:-1}"
RUN_PLIP_ALL_POSES="${RUN_PLIP_ALL_POSES:-1}"
TOP_CLUSTERS_FOR_DETAILED_ANALYSIS="${TOP_CLUSTERS_FOR_DETAILED_ANALYSIS:-3}"

# Descriptive cross-ligand spatial-region classification parameters.  These
# are workflow settings, not universal biological decision thresholds.
COMPARISON_CENTROID_THRESHOLD_A="${COMPARISON_CENTROID_THRESHOLD_A:-5.0}"
COMPARISON_RESIDUE_JACCARD_THRESHOLD="${COMPARISON_RESIDUE_JACCARD_THRESHOLD:-0.3}"
COMPARISON_FINGERPRINT_THRESHOLD="${COMPARISON_FINGERPRINT_THRESHOLD:-0.3}"

DOCK_RESULT_ROOT="${DOCK_RESULT_ROOT:-$PROJECT_ROOT/_autodock4_batch}"
ANALYSIS_ROOT="${ANALYSIS_ROOT:-$PROJECT_ROOT/_full_docking_analysis}"

# Paths retained from the supplied production AutoDock4 script.
OBABEL="${OBABEL:?Set OBABEL to the local Open Babel executable}"
PYTHONSH="${PYTHONSH:?Set PYTHONSH to the local MGLTools pythonsh executable}"
PREP_LIGAND="${PREP_LIGAND:?Set PREP_LIGAND to local prepare_ligand4.py}"
PREP_RECEPTOR="${PREP_RECEPTOR:?Set PREP_RECEPTOR to local prepare_receptor4.py}"
AUTOGRID="${AUTOGRID:-$PROJECT_ROOT/autogrid4}"
AUTODOCK="${AUTODOCK:-$PROJECT_ROOT/autodock4}"

export PROJECT_ROOT PIPELINE_PROJECT_DIR CONDA_BASE POST_ENV_NAME DOCK_CPUS POST_CPUS PLIP_PARALLEL
export GA_RUN_TOTAL GA_NUM_EVALS GA_NUM_GENERATIONS GA_POP_SIZE RMSTOL
export RMSD_PRIMARY_CUTOFF RMSD_SENSITIVITY_CUTOFFS SKIP_EXISTING
export RUN_PLIP_ALL_POSES TOP_CLUSTERS_FOR_DETAILED_ANALYSIS
export COMPARISON_CENTROID_THRESHOLD_A COMPARISON_RESIDUE_JACCARD_THRESHOLD COMPARISON_FINGERPRINT_THRESHOLD
export DOCK_RESULT_ROOT ANALYSIS_ROOT OBABEL PYTHONSH PREP_LIGAND PREP_RECEPTOR AUTOGRID AUTODOCK
